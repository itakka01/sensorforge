#!/bin/bash
# Maintains archive_tools_manifest.h: the list of released EXAPAN converter
# versions (version marker + SHA-256) that the firmware accepts from SD:/tools.
#
#   tools/update_archive_tools_manifest.sh          add the current .cmd if new
#   tools/update_archive_tools_manifest.sh --check  only verify (exit 1 if stale)
#
# Rules: every content change of exapan_archive_convert.cmd needs a higher
# "# EXAPAN_CONVERTER_VERSION=<n>" line. Older entries stay in the list so the
# firmware can report them as outdated instead of unknown.
set -euo pipefail
ROOT="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd -P)"
CMD="$ROOT/exapan_archive_convert.cmd"
HDR="$ROOT/archive_tools_manifest.h"
CHECK=0; [[ "${1:-}" == "--check" ]] && CHECK=1

[[ -f "$CMD" ]] || { echo "[ERROR] $CMD not found" >&2; exit 2; }
version="$(grep -m1 -E '^# EXAPAN_CONVERTER_VERSION=[0-9]+[[:space:]]*$' "$CMD" | sed -E 's/.*=([0-9]+).*/\1/' || true)"
[[ -n "$version" && "$version" -gt 0 ]] || { echo "[ERROR] Missing '# EXAPAN_CONVERTER_VERSION=<n>' line in $CMD" >&2; exit 2; }
sha="$(sha256sum "$CMD" | cut -d' ' -f1)"

entries=""
[[ -f "$HDR" ]] && entries="$(grep -oE '\{ *[0-9]+, *"[0-9a-f]{64}" *\}' "$HDR" | sed -E 's/[{}" ]//g' || true)"

if grep -qx "$version,$sha" <<< "$entries"; then
    echo "[OK] archive_tools_manifest.h is current (converter v$version)"; exit 0
fi
if grep -q "^$version," <<< "$entries"; then
    echo "[ERROR] Converter v$version is already released with a different SHA-256." >&2
    echo "        Increase EXAPAN_CONVERTER_VERSION in exapan_archive_convert.cmd." >&2
    exit 1
fi
if (( CHECK )); then
    echo "[ERROR] archive_tools_manifest.h is stale: converter v$version is not listed." >&2
    echo "        Run tools/update_archive_tools_manifest.sh" >&2
    exit 1
fi

entries="$(printf '%s\n%s,%s\n' "$entries" "$version" "$sha" | sed '/^$/d' | sort -t, -k1,1n)"
current="$(tail -n1 <<< "$entries" | cut -d, -f1)"
{
    echo "#pragma once"
    echo "// GENERATED by tools/update_archive_tools_manifest.sh - do not edit by hand."
    echo "// Released EXAPAN converter versions accepted from SD:/tools (day ZIP)."
    echo "#include <stdint.h>"
    echo ""
    echo "struct ArchiveToolRelease { uint16_t version; const char *sha256Hex; };"
    echo ""
    echo "static constexpr uint16_t kExapanConverterCurrentVersion = $current;"
    echo "static const ArchiveToolRelease kExapanConverterReleases[] = {"
    while IFS=, read -r v s; do echo "    { $v, \"$s\" },"; done <<< "$entries"
    echo "};"
} > "$HDR.tmp"
mv "$HDR.tmp" "$HDR"
echo "[OK] Added converter v$version to archive_tools_manifest.h (current: v$current)"
